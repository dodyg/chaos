// FullCalendar 6 injects its CSS from JavaScript at run time. The desktop host's content policy refuses
// injected style tags, so the same CSS is shipped as a normal stylesheet. Run after changing the pinned version:
//   node scripts/extract-fullcalendar-css.mjs
import { readFileSync, writeFileSync } from "node:fs";

const files = ["core/internal-common.js", "daygrid/internal.js", "timegrid/internal.js", "list/internal.js"];
const marker = "css_248z = ";
let out = "/* Generated by scripts/extract-fullcalendar-css.mjs from @fullcalendar 6.1.22 (MIT). Do not edit. */\n";
for (const file of files) {
  const text = readFileSync(new URL(`../node_modules/@fullcalendar/${file}`, import.meta.url), "utf8");
  const start = text.indexOf(marker);
  if (start < 0) throw new Error(`No stylesheet found in ${file}`);
  // The value is one JSON-compatible double-quoted string literal; find its closing quote.
  let i = start + marker.length;
  if (text[i] !== '"') throw new Error(`Unexpected stylesheet literal in ${file}`);
  let end = i + 1;
  while (text[end] !== '"') end += text[end] === "\\" ? 2 : 1;
  out += JSON.parse(text.slice(i, end + 1)) + "\n";
}
writeFileSync(new URL("../src/fullcalendar.css", import.meta.url), out);
console.log(`wrote ${out.length} characters`);
