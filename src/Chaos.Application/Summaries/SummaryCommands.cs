namespace Chaos.Application.Summaries;

public sealed record SummarySettings(TimeOnly? MorningTime, TimeOnly? EveningTime, DayOfWeek? WeeklyDay, DayOfWeek FirstWeekday, long Version, string ZoneId);

/// <param name="MorningTime">Null turns the scheduled morning summary off (it can still be made by hand).</param>
/// <param name="EveningTime">Null turns the scheduled evening and weekly summaries' time off; weekly then uses 18:00.</param>
/// <param name="WeeklyDay">Null turns the scheduled weekly summary off.</param>
public sealed record UpdateSummarySettingsCommand(string OperationId, long ExpectedVersion, TimeOnly? MorningTime, TimeOnly? EveningTime, DayOfWeek? WeeklyDay);

/// <summary>Generates (or regenerates, as a new revision) the summary of the period containing <see cref="Date"/>.</summary>
public sealed record GenerateSummaryCommand(string OperationId, SummaryKind Kind, DateOnly Date);

public sealed record SummaryRevisionInfo(string Id, long Revision, DateTimeOffset GeneratedAtUtc, DateTimeOffset CapturedThroughUtc, SummaryTrigger Trigger);

/// <summary>Plain counts for the journal list and prompts.</summary>
public sealed record SummaryCounts(int CompletionEvents, int StillDone, int Unfinished, int DiaryUpdates, int Deadlines, int Waiting, int Selected, bool Quiet)
{
    public static SummaryCounts Of(SummaryFacts facts) => new(
        facts.Completions.Count,
        facts.Completions.Where(item => item.StillDone).Select(item => item.Task.TaskId).Distinct(StringComparer.Ordinal).Count(),
        facts.Unfinished.Count,
        facts.DiaryUpdateCount,
        facts.Deadlines.Count,
        facts.Waiting.Count,
        facts.Selected.Count,
        facts.IsQuiet);
}

public sealed record SummaryView(SummaryRecord Summary, SummaryFacts Facts, SummaryCounts Counts, IReadOnlyList<SummaryRevisionInfo> Revisions, bool IsLatest);

public sealed record JournalEntry(SummaryRecord Summary, SummaryCounts Counts);

/// <param name="NextCursor">Opaque cursor for the next (older) page; null at the end.</param>
public sealed record JournalPage(IReadOnlyList<JournalEntry> Entries, string? NextCursor);

public enum CarryOverTarget { Day = 0, Week = 1 }

/// <param name="StillOpen">The task is open and not deleted now; finished or deleted tasks cannot be carried.</param>
/// <param name="AlreadyPlanned">It is already on the target day, or in the target week's plan or draft.</param>
public sealed record CarryOverCandidate(SummaryTaskFact Task, bool StillOpen, bool AlreadyPlanned);

/// <summary>What carrying over would do: the target day (or week start) and each unfinished task.</summary>
public sealed record CarryOverPreview(string SummaryId, CarryOverTarget Target, DateOnly TargetDate, IReadOnlyList<CarryOverCandidate> Candidates);

public sealed record SummaryCarryOverCommand(string OperationId, string SummaryId, IReadOnlyList<string> TaskIds);

/// <param name="Added">Personal records created (My Day items, or tasks added to the week's draft).</param>
/// <param name="Skipped">Chosen tasks that were already there, finished or deleted.</param>
public sealed record SummaryCarryOverResult(CarryOverTarget Target, DateOnly TargetDate, int Added, int Skipped, bool Replayed);

/// <summary>A summary whose "ready" prompt is due: the newest one per kind.</summary>
public sealed record SummaryPrompt(SummaryRecord Summary, SummaryCounts Counts);

/// <summary>
/// Plain daily and weekly summaries and the journal (PLAN §12, work package 11). Facts are
/// built in C# from append-only history and stored once per revision; there is no AI and no
/// network. Scheduled summaries are generated by the host's background tick at the morning,
/// evening and weekly times while Chaos runs; a missed period is generated once at the next
/// start. Unique period keys make generation idempotent: a scheduled or catch-up run never
/// adds a revision to a period that has one, while an explicit regeneration adds the next
/// revision and keeps the earlier ones. Carry-over only creates the chosen next-day or
/// next-week personal records, once each; it never edits a task's planned or due date.
/// </summary>
public sealed class SummaryCommands(IApplicationStore store, IIdGenerator ids, TimeProvider clock)
{
    /// <summary>Version of the facts shape and the UI strings that render it.</summary>
    public const int ResourceVersion = 1;
    public const int MaxJournalPage = 50;

    private readonly MyWeekCommands _weeks = new(store, ids, clock);

    public async Task<SummarySettings> GetSettingsAsync(CancellationToken ct = default) =>
        await store.QueryAsync(async (session, token) => SettingsOf(await ReminderCommands.RequireProfileAsync(session, token)), ct);

    public async Task<SummarySettings> UpdateSettingsAsync(UpdateSummarySettingsCommand command, CancellationToken ct = default)
    {
        ReminderCommands.RequireOperation(command.OperationId);
        if (command.WeeklyDay is { } day && !Enum.IsDefined(day))
        {
            throw AppException.Validation("weeklyDay", "Choose a weekday for the weekly summary.");
        }

        var normalized = command with
        {
            MorningTime = command.MorningTime is { } morning ? new TimeOnly(morning.Hour, morning.Minute) : null,
            EveningTime = command.EveningTime is { } evening ? new TimeOnly(evening.Hour, evening.Minute) : null,
        };
        await store.ExecuteAsync(async (session, token) =>
        {
            var now = clock.GetUtcNow();
            var current = await ReminderCommands.RequireProfileAsync(session, token);
            var (version, _) = await TaskMutationSupport.ReplayOrRunAsync(session, current.Id, normalized.OperationId, "summary.settings", normalized, now, async inner =>
            {
                if (current.Version != normalized.ExpectedVersion)
                {
                    throw AppException.VersionConflict("Settings changed elsewhere. Refresh and try again.");
                }

                var updated = current with
                {
                    MorningTime = normalized.MorningTime,
                    SummaryTime = normalized.EveningTime,
                    WeeklySummaryDay = normalized.WeeklyDay,
                    Version = current.Version + 1,
                    UpdatedAtUtc = now,
                };
                _ = await session.Profiles.UpdateSummarySettingsAsync(updated, current.Version, inner)
                    ?? throw AppException.VersionConflict("Settings changed elsewhere. Refresh and try again.");
                return updated.Version;
            }, token);
            return version;
        }, ct);
        return await GetSettingsAsync(ct);
    }

    /// <summary>
    /// Generates every scheduled summary that is due and missing: today's morning summary once
    /// its time has passed, today's evening summary once its time has passed plus up to seven
    /// missed earlier dates, and the latest week whose weekly summary is due. Only the newest
    /// new summary of each kind gets a "ready" prompt, at the first instant outside quiet
    /// hours, so a long absence does not flood the person. Safe to call on every tick.
    /// </summary>
    public async Task<IReadOnlyList<SummaryRecord>> GenerateDueAsync(CancellationToken ct = default) =>
        await store.ExecuteAsync<IReadOnlyList<SummaryRecord>>(async (session, token) =>
        {
            var now = clock.GetUtcNow();
            var context = await TaskQueries.ContextAsync(session, now, token);
            var profile = context.Profile;
            var zone = context.Zone;
            var today = context.Today;
            var earliest = TaskQueries.LocalDate(profile.CreatedAtUtc, zone);
            var created = new List<SummaryRecord>();

            async Task EnsureAsync(SummaryKind kind, DateOnly start, SummaryTrigger trigger, bool prompt)
            {
                if (await session.Summaries.FindLatestAsync(profile.Id, kind, start, token) is not null)
                {
                    return;
                }

                var row = await CreateAsync(session, context, kind, start, 1, trigger, prompt ? ReminderSync.DeliveryInstant(profile, zone, now) : null, now, token);
                if (await session.Summaries.TryAddAsync(row, token))
                {
                    created.Add(row);
                }
            }

            if (profile.MorningTime is { } morning && now >= SummarySchedule.At(today, morning, zone) && today >= earliest)
            {
                await EnsureAsync(SummaryKind.Morning, today, SummaryTrigger.Scheduled, prompt: true);
            }

            if (profile.SummaryTime is { } evening)
            {
                var dates = SummarySchedule.DailyDatesDue(today, now, evening, zone, earliest);
                var missing = new List<DateOnly>();
                foreach (var date in dates)
                {
                    if (await session.Summaries.FindLatestAsync(profile.Id, SummaryKind.Daily, date, token) is null)
                    {
                        missing.Add(date);
                    }
                }

                // Oldest first so the journal fills in order; the newest gets the prompt.
                foreach (var date in missing.OrderBy(date => date))
                {
                    await EnsureAsync(SummaryKind.Daily, date, date == today ? SummaryTrigger.Scheduled : SummaryTrigger.CatchUp, prompt: date == missing.Max());
                }
            }

            if (profile.WeeklySummaryDay is { } weeklyDay)
            {
                var time = profile.SummaryTime ?? SummarySchedule.DefaultEveningTime;
                var current = await WeekResolution.StartForAsync(session, profile, today, token);
                var previous = await WeekResolution.StartForAsync(session, profile, current.AddDays(-1), token);
                foreach (var weekStart in new[] { current, previous })
                {
                    var dueDate = SummarySchedule.WeeklyDueDate(weekStart, weeklyDay);
                    var dueAt = SummarySchedule.At(dueDate, time, zone);
                    if (now >= dueAt && WeekCalendar.EndOf(weekStart) >= earliest)
                    {
                        await EnsureAsync(SummaryKind.Weekly, weekStart, dueDate == today ? SummaryTrigger.Scheduled : SummaryTrigger.CatchUp, prompt: true);
                        break; // only the latest due week
                    }
                }
            }

            return created;
        }, ct);

    /// <summary>
    /// Explicitly generates the summary of the period containing the date, as the next
    /// revision. Earlier revisions stay. A period that has not begun cannot be summarized.
    /// </summary>
    public async Task<SummaryView> GenerateAsync(GenerateSummaryCommand command, CancellationToken ct = default)
    {
        ReminderCommands.RequireOperation(command.OperationId);
        if (!Enum.IsDefined(command.Kind))
        {
            throw AppException.Validation("kind", "Choose a morning, daily or weekly summary.");
        }

        var (id, _) = await store.ExecuteAsync(async (session, token) =>
        {
            var now = clock.GetUtcNow();
            var context = await TaskQueries.ContextAsync(session, now, token);
            return await TaskMutationSupport.ReplayOrRunAsync(session, context.Profile.Id, command.OperationId, "summary.generate",
                new { kind = command.Kind, date = command.Date }, now, async inner =>
                {
                    var start = command.Kind == SummaryKind.Weekly
                        ? await WeekResolution.StartForAsync(session, context.Profile, command.Date, inner)
                        : command.Date;
                    if (start > context.Today)
                    {
                        throw AppException.Validation("date", "That period has not started yet. Choose today or an earlier date.");
                    }

                    var latest = await session.Summaries.FindLatestAsync(context.Profile.Id, command.Kind, start, inner);
                    var row = await CreateAsync(session, context, command.Kind, start, (latest?.Revision ?? 0) + 1, SummaryTrigger.Manual, null, now, inner);
                    if (!await session.Summaries.TryAddAsync(row, inner))
                    {
                        throw AppException.OperationConflict("This summary was generated at the same moment. Refresh the journal.");
                    }

                    return row.Id;
                }, token);
        }, ct);
        return await GetAsync(id, ct);
    }

    public async Task<SummaryView> GetAsync(string summaryId, CancellationToken ct = default) =>
        await store.QueryAsync(async (session, token) =>
        {
            var profile = await ReminderCommands.RequireProfileAsync(session, token);
            var summary = await session.Summaries.GetAsync(summaryId, token);
            if (summary is null || summary.ProfileId != profile.Id)
            {
                throw AppException.NotFound("That summary no longer exists. Refresh the journal.");
            }

            var revisions = await session.Summaries.ListRevisionsAsync(profile.Id, summary.Kind, summary.PeriodStart, token);
            var facts = FactsOf(summary);
            return new SummaryView(summary, facts, SummaryCounts.Of(facts),
                [.. revisions.Select(row => new SummaryRevisionInfo(row.Id, row.Revision, row.GeneratedAtUtc, row.CapturedThroughUtc, row.Trigger))],
                revisions[0].Id == summary.Id);
        }, ct);

    /// <summary>The newest revision of the summary of one period, if it exists.</summary>
    public async Task<SummaryView?> FindAsync(SummaryKind kind, DateOnly date, CancellationToken ct = default)
    {
        var id = await store.QueryAsync(async (session, token) =>
        {
            var profile = await ReminderCommands.RequireProfileAsync(session, token);
            var start = kind == SummaryKind.Weekly ? await WeekResolution.StartForAsync(session, profile, date, token) : date;
            return (await session.Summaries.FindLatestAsync(profile.Id, kind, start, token))?.Id;
        }, ct);
        return id is null ? null : await GetAsync(id, ct);
    }

    /// <summary>The journal, newest period first; weekly summaries sit at the end of their week.</summary>
    public async Task<JournalPage> JournalAsync(string? cursor, int limit, CancellationToken ct = default)
    {
        var (endBefore, kindBefore) = ParseCursor(cursor);
        var size = Math.Clamp(limit, 1, MaxJournalPage);
        return await store.QueryAsync(async (session, token) =>
        {
            var profile = await ReminderCommands.RequireProfileAsync(session, token);
            var rows = await session.Summaries.ListJournalAsync(profile.Id, endBefore, kindBefore, size + 1, token);
            var page = rows.Take(size).Select(row => new JournalEntry(row, SummaryCounts.Of(FactsOf(row)))).ToList();
            var next = rows.Count > size ? $"{StorageFormats.Date(page[^1].Summary.PeriodEnd)}|{(int)page[^1].Summary.Kind}" : null;
            return new JournalPage(page, next);
        }, ct);
    }

    /// <summary>Summaries whose "ready" prompt is due and not yet seen: the newest per kind.</summary>
    public async Task<IReadOnlyList<SummaryPrompt>> PromptsAsync(CancellationToken ct = default) =>
        await store.QueryAsync<IReadOnlyList<SummaryPrompt>>(async (session, token) =>
        {
            var profile = await ReminderCommands.RequireProfileAsync(session, token);
            return [.. (await session.Summaries.ListPromptsDueAsync(profile.Id, clock.GetUtcNow(), token))
                .GroupBy(row => row.Kind)
                .Select(group => group.OrderByDescending(row => row.PeriodStart).First())
                .OrderByDescending(row => row.PromptAtUtc)
                .Select(row => new SummaryPrompt(row, SummaryCounts.Of(FactsOf(row))))];
        }, ct);

    /// <summary>The person opened or dismissed a prompt; older unseen prompts of the same kind go with it.</summary>
    public async Task DismissPromptAsync(string summaryId, CancellationToken ct = default) =>
        await store.ExecuteAsync(async (session, token) =>
        {
            var now = clock.GetUtcNow();
            var profile = await ReminderCommands.RequireProfileAsync(session, token);
            if (await session.Summaries.GetAsync(summaryId, token) is not { } summary || summary.ProfileId != profile.Id)
            {
                return 0;
            }

            foreach (var row in await session.Summaries.ListPromptsDueAsync(profile.Id, now, token))
            {
                if (row.Kind == summary.Kind && row.PeriodStart <= summary.PeriodStart)
                {
                    await session.Summaries.MarkPromptSeenAsync(row.Id, now, token);
                }
            }

            await session.Summaries.MarkPromptSeenAsync(summary.Id, now, token);
            return 1;
        }, ct);

    public async Task<CarryOverPreview> PreviewCarryOverAsync(string summaryId, CancellationToken ct = default) =>
        await store.QueryAsync(async (session, token) =>
        {
            var context = await TaskQueries.ContextAsync(session, clock.GetUtcNow(), token);
            var summary = await RequireCarryableAsync(session, context, summaryId, token);
            var (target, date) = await TargetAsync(session, context, summary, token);
            var planned = await PlannedOnTargetAsync(session, context, target, date, token);
            var candidates = new List<CarryOverCandidate>();
            foreach (var item in FactsOf(summary).Unfinished)
            {
                var task = await session.Tasks.GetAsync(item.Task.TaskId, token);
                candidates.Add(new CarryOverCandidate(item.Task, task is { IsTerminal: false }, planned.Contains(item.Task.TaskId)));
            }

            return new CarryOverPreview(summary.Id, target, date, candidates);
        }, ct);

    /// <summary>
    /// Carries the chosen unfinished tasks of a daily summary onto the next My Day (today when
    /// that date has passed), or of a weekly summary into the next week's plan draft (to be
    /// confirmed in My Week). Each task is placed at most once; finished, deleted and already
    /// planned tasks are skipped. Task dates are never changed.
    /// </summary>
    public async Task<SummaryCarryOverResult> CarryOverAsync(SummaryCarryOverCommand command, CancellationToken ct = default)
    {
        ReminderCommands.RequireOperation(command.OperationId);
        if (command.TaskIds is null || command.TaskIds.Count == 0)
        {
            throw AppException.Validation("taskIds", "Choose at least one task to carry over.");
        }

        var chosen = command.TaskIds.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToArray();
        var (result, replayed) = await store.ExecuteAsync(async (session, token) =>
        {
            var now = clock.GetUtcNow();
            var context = await TaskQueries.ContextAsync(session, now, token);
            return await TaskMutationSupport.ReplayOrRunAsync(session, context.Profile.Id, command.OperationId, "summary.carryOver",
                new { summaryId = command.SummaryId, taskIds = chosen }, now, async inner =>
                {
                    var summary = await RequireCarryableAsync(session, context, command.SummaryId, inner);
                    var unfinished = FactsOf(summary).Unfinished.Select(item => item.Task.TaskId).ToHashSet(StringComparer.Ordinal);
                    if (chosen.Any(id => !unfinished.Contains(id)))
                    {
                        throw AppException.Validation("taskIds", "Only unfinished tasks of this summary can be carried over. Refresh and choose again.");
                    }

                    var (target, date) = await TargetAsync(session, context, summary, inner);
                    var open = new List<string>();
                    foreach (var taskId in chosen)
                    {
                        if (await session.Tasks.GetAsync(taskId, inner) is { IsTerminal: false } task && task.SpaceId == context.Space.Id)
                        {
                            open.Add(taskId);
                        }
                    }

                    int added;
                    if (target == CarryOverTarget.Day)
                    {
                        var plan = await DayPlanning.EnsurePlanAsync(session, ids, context.Profile.Id, date, now, inner);
                        added = 0;
                        foreach (var taskId in open)
                        {
                            added += await DayPlanning.PlaceAsync(session, ids, plan, taskId, DayPlanItemOrigin.CarryOver, now, inner) ? 1 : 0;
                        }
                    }
                    else
                    {
                        added = await _weeks.CarryIntoDraftAsync(session, context, date, open, now, inner);
                    }

                    return new SummaryCarryOverResult(target, date, added, chosen.Length - added, Replayed: false);
                }, token);
        }, ct);
        return result with { Replayed = replayed };
    }

    // ---------------------------------------------------------------- helpers

    private async Task<SummaryRecord> CreateAsync(
        IDataSession session, TaskQueries.QueryContext context, SummaryKind kind, DateOnly start, long revision, SummaryTrigger trigger,
        DateTimeOffset? promptAt, DateTimeOffset now, CancellationToken token)
    {
        var end = kind == SummaryKind.Weekly ? WeekCalendar.EndOf(start) : start;
        var startUtc = TaskQueries.StartOfLocalDayUtc(context.Zone, start);
        var endUtc = TaskQueries.StartOfLocalDayUtc(context.Zone, end.AddDays(1));
        var captured = now < startUtc ? startUtc : now > endUtc ? endUtc : now;
        var period = new SummaryPeriod(kind, start, end, startUtc, endUtc, captured);
        var facts = await SummaryFactsBuilder.BuildAsync(session, context, period, token);
        return new SummaryRecord
        {
            Id = StorageFormats.Id(ids.NewId()),
            ProfileId = context.Profile.Id,
            Kind = kind,
            PeriodStart = start,
            PeriodEnd = end,
            Revision = revision,
            PeriodStartUtc = startUtc,
            PeriodEndUtc = endUtc,
            CapturedThroughUtc = captured,
            ZoneId = context.Zone.Id,
            Trigger = trigger,
            FactsJson = StoredJsonFormats.Snapshot(facts),
            ResourceVersion = ResourceVersion,
            GeneratedAtUtc = now,
            PromptAtUtc = promptAt,
        };
    }

    private static SummaryFacts FactsOf(SummaryRecord summary) =>
        StoredJsonFormats.ReadSnapshot<SummaryFacts>(summary.FactsJson)
        ?? throw new AppException(AppErrorKind.StorageUnavailable, "This summary could not be read.");

    private static async Task<SummaryRecord> RequireCarryableAsync(IDataSession session, TaskQueries.QueryContext context, string summaryId, CancellationToken token)
    {
        var summary = await session.Summaries.GetAsync(summaryId, token);
        if (summary is null || summary.ProfileId != context.Profile.Id)
        {
            throw AppException.NotFound("That summary no longer exists. Refresh the journal.");
        }

        return summary.Kind == SummaryKind.Morning
            ? throw AppException.Validation("summaryId", "A morning summary looks ahead; carry over from the evening or weekly summary.")
            : summary;
    }

    /// <summary>The next date after a daily summary (today when it has passed), or the next week's start after a weekly one.</summary>
    private static async Task<(CarryOverTarget Target, DateOnly Date)> TargetAsync(IDataSession session, TaskQueries.QueryContext context, SummaryRecord summary, CancellationToken token)
    {
        var next = summary.PeriodEnd.AddDays(1);
        var date = next < context.Today ? context.Today : next;
        return summary.Kind == SummaryKind.Weekly
            ? (CarryOverTarget.Week, await WeekResolution.StartForAsync(session, context.Profile, date, token))
            : (CarryOverTarget.Day, date);
    }

    private async Task<HashSet<string>> PlannedOnTargetAsync(IDataSession session, TaskQueries.QueryContext context, CarryOverTarget target, DateOnly date, CancellationToken token)
    {
        if (target == CarryOverTarget.Week)
        {
            return await MyWeekCommands.PlannedTaskIdsAsync(session, context.Profile.Id, date, token);
        }

        var planned = new HashSet<string>(StringComparer.Ordinal);
        if (await session.DayPlans.FindAsync(context.Profile.Id, date, token) is { } plan)
        {
            foreach (var item in await session.DayPlans.ListItemsAsync(plan.Id, includeRemoved: false, token))
            {
                planned.Add(item.TaskId);
            }
        }

        return planned;
    }

    private static (DateOnly? EndBefore, SummaryKind? KindBefore) ParseCursor(string? cursor)
    {
        if (string.IsNullOrWhiteSpace(cursor))
        {
            return (null, null);
        }

        var parts = cursor.Split('|');
        return parts.Length == 2 && StorageFormats.ParseDate(parts[0]) is { } date && int.TryParse(parts[1], out var kind) && Enum.IsDefined((SummaryKind)kind)
            ? (date, (SummaryKind)kind)
            : throw AppException.Validation("cursor", "The journal page could not be found. Reload the journal.");
    }

    private static SummarySettings SettingsOf(ProfileRecord profile) =>
        new(profile.MorningTime, profile.SummaryTime, profile.WeeklySummaryDay, profile.FirstWeekday, profile.Version, profile.ZoneId);
}
